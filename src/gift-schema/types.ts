/**
 * GiftContentV1 (arch-web-react-motion.md §6.2; FRAMEWORK §7.5; owner: scaffold). React-free.
 * zod-free mirror of the server schema; `validateGift` in validate.ts is the runtime check.
 * Content is versioned (`v`); the player supports N and N−1 via migrate().
 */
export const GIFT_SCHEMA_VERSION = 1 as const;

export type Mechanic = 'envelope' | 'box' | 'booth' | 'notebook';
/** data-theme values (design-tokens.json → themes). */
export type ThemeId = 'garden-envelope' | 'sweet-gingham' | 'booth-stripes' | 'cloud-lyric' | 'oli-notebook' | (string & {});
/** Letter font roles the creator may pick (FRAMEWORK §3.4 picker). */
export type LetterFont = 'handBody' | 'scriptSignature' | 'scriptDisplay' | 'handMarker' | 'displayExtruded';

export interface Names {
  /** Sender display name (NFC, ≤24 graphemes). */
  from: string;
  /** Recipient display name / nickname. */
  to: string;
  /** Sender's self pronoun ("anh", "em", "tớ", "mình" …). */
  self: string;
  /** Pronoun for the recipient ("em", "anh", "cậu", "bạn" …). */
  you: string;
  /** Particle: 'nhe' → "nhé" (north), 'nha' → "nha" (south). */
  tone: 'nhe' | 'nha';
  /** Pronoun set id the creator picked (vi.json → pronouns: 'anh-em' | 'em-anh' | 'to-cau' | 'minh-ban' | 'none').
   *  Lets {we}/{We} and the north 'to-cau' override resolve; older links infer it from self/you. */
  pronouns?: string;
}

/** A media reference. Server: uuid resolved to a signed URL by /api/gift/[slug]/open. Local starter:
 *  'ph:<n>' (procedural placeholder art) or a small 'data:' URL. Resolve with resolveMedia(). */
export type MediaRef = string;

export interface Photo { ref: MediaRef; caption?: string }

export interface LetterPage { kind: 'letter'; greeting: string; body: string; signature: string; font?: LetterFont }
export interface MemoriesPage { kind: 'memories'; title?: string; photos: Photo[] }
export interface SongsPage { kind: 'songs'; tracks: { title: string; url: string; startAt?: number }[] }
export interface VoicePage { kind: 'voice'; ref: MediaRef; durationSec: number }
export interface MapPage { kind: 'map'; plate: string; pins: { x: number; y: number; place: string; date?: string }[] }
export interface TreatNotesPage { kind: 'treats'; notes: string[] }
export interface NotebookPage { kind: 'notebook'; pages: { text: string; object?: MediaRef }[] }
export interface DaysPage { kind: 'days'; startDate: string; countFirstDay?: boolean }

export type GiftPage = LetterPage | MemoriesPage | SongsPage | VoicePage | MapPage | TreatNotesPage | NotebookPage | DaysPage;
export type GiftPageKind = GiftPage['kind'];

export interface GiftContentV1 {
  /** Schema version; absent in the docs fixture (treated as 1). */
  v?: 1;
  /** Stable id used for seeding fx (hashSeed(id)); generated by the creator. */
  id?: string;
  mechanic: Mechanic;
  theme: ThemeId;
  locale: 'vi' | 'en';
  names: Names;
  pages: GiftPage[];
  mediaRefs: MediaRef[];
  /** Booth mechanic: composited strips. */
  strips?: MediaRef[];
  finale: { enabled: boolean };
  /** Optional gates (server-enforced in production; local starter only shows the UI). */
  unlockAt?: string;
  secret?: { question: string; hint?: string; answer?: string };
}

export type GiftContent = GiftContentV1;
